import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { minifyContractRouter } from '@orpc/contract';

/** Evaluate only the portable graph, then discard schemas from runtime metadata. */
export async function generatePilotRouting() {
	const result = await build({
		stdin: {
			contents: "export { pilotContract } from '../features/index/backend/api.contract.ts'; export { requestRoutes } from '../features/api/shared/api-routing.ts';",
			resolveDir: fileURLToPath(new URL('.', import.meta.url)),
		},
		bundle: true, platform: 'browser', format: 'esm', write: false,
	});
	const { pilotContract, requestRoutes } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
	const minified = minifyContractRouter(pilotContract);
	if (JSON.stringify(requestRoutes(pilotContract)) !== JSON.stringify(requestRoutes(minified))) {
		throw new Error('Minified routing does not preserve APIClient aliases');
	}
	const source = `// Generated by generate-pilot-routing.mjs; contains routing metadata only.\nimport type { AnyContractRouter } from '@orpc/contract';\n\nexport default ${JSON.stringify(minified, null, '\t')} satisfies AnyContractRouter;\n`;
	fs.writeFileSync(new URL('./src/autogen/pilot-routing.ts', import.meta.url), source);
}
