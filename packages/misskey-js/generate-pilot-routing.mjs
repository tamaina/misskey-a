import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { enhanceContractRouter, isContractProcedure, minifyContractRouter } from '@orpc/contract';
import { fallbackORPCErrorStatus } from '@orpc/client';

/** Evaluate only the portable graph, then discard schemas from runtime metadata. */
export async function generatePilotRouting() {
	const result = await build({
		stdin: {
			contents: "export { pilotContract } from '../features/index/backend/api.contract.ts'; export { requestRoutes, nullableResponsePaths } from '../features/api/shared/api-routing.ts'; export { apiErrorData } from '../features/api/backend/transport/errors.schema.ts';",
			resolveDir: fileURLToPath(new URL('.', import.meta.url)),
		},
		bundle: true, platform: 'browser', format: 'esm', write: false,
	});
	const { pilotContract, requestRoutes, nullableResponsePaths, apiErrorData } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
	// The official minifier drops errors. Restore code/status metadata with the
	// supported enhancer; schemas are never retained or mutated in runtime metadata.
	function compact(router) {
		if (!isContractProcedure(router)) return Object.fromEntries(Object.entries(router).map(([key, value]) => [key, compact(value)]));
		const errorMap = Object.fromEntries(Object.entries(router['~orpc'].errorMap).map(([code, definition]) => {
			if (!definition || definition.data !== apiErrorData) throw new Error('Pilot error decoder requires the shared Misskey error DTO');
			return [code, { status: fallbackORPCErrorStatus(code, definition.status) }];
		}));
		return enhanceContractRouter(minifyContractRouter(router), { errorMap });
	}
	const minified = compact(pilotContract);
	if (JSON.stringify(requestRoutes(pilotContract)) !== JSON.stringify(requestRoutes(minified))) {
		throw new Error('Minified routing does not preserve APIClient aliases');
	}
	const nullablePaths = await nullableResponsePaths(pilotContract);
	const source = `// Generated by generate-pilot-routing.mjs; contains routing and declared-error status metadata only.\nimport type { AnyContractRouter } from '@orpc/contract';\n\nexport default ${JSON.stringify(minified, null, '\t')} satisfies AnyContractRouter;\n\nexport const nullableResponses: readonly (readonly string[])[] = ${JSON.stringify(nullablePaths, null, '\t')};\n`;
	fs.writeFileSync(new URL('./src/autogen/pilot-routing.ts', import.meta.url), source);
}
